export function normalizeLocale(value?: string | null): Locale {
  return value?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
}

export function translate(locale: Locale, key: TranslationKey): string {
  return (locale === 'zh-CN' ? zh : en)[key];
}

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function currentLocale(): Locale {
  if (typeof window === 'undefined') return 'en-US';
  try { return normalizeLocale(window.localStorage.getItem('javarailways.locale') || window.navigator?.language); }
  catch { return normalizeLocale(window.navigator?.language); }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, updateLocale] = useState<Locale>(currentLocale);
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale(next) {
      updateLocale(next);
      if (typeof window !== 'undefined') window.localStorage.setItem('javarailways.locale', next);
    },
    t: (key) => translate(locale, key),
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}
